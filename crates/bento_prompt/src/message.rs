//! Conversation input: roles, messages, and the options that shape a session
//! or one operation.

use oxilangtag::LanguageTag;
use serde_json::Value;

use crate::{Error, ErrorKind};

/// Availability of the on-device model for a given configuration.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Availability {
    /// The model can be used now.
    Available,
    /// The model cannot be used, whatever the reason.
    Unavailable,
}

/// The author of a message.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Role {
    /// Instructions that govern the whole conversation.
    System,
    /// Input from the application or its user.
    User,
    /// A turn generated by, or attributed to, the model.
    Assistant,
}

/// One text message of a conversation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Message {
    /// Who the message is attributed to.
    pub role: Role,
    /// The message text.
    pub content: String,
}

/// One declared input or output expectation.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Expected {
    /// Draft content type this expectation names, such as `text`.
    pub kind: String,
    /// Language tags the caller expects to use.
    pub languages: Vec<String>,
}

/// Configuration for a new session.
#[derive(Debug, Clone, Default)]
pub struct CreateOptions {
    /// Conversation history to load without generating replies.
    pub initial_prompts: Vec<Message>,
    /// Expected input content types and languages.
    pub expected_inputs: Vec<Expected>,
    /// Expected output content types and languages.
    pub expected_outputs: Vec<Expected>,
}

/// Configuration for one generation or measurement.
#[derive(Debug, Clone, Default)]
pub struct PromptOptions {
    /// JSON Schema, from the supported subset, that the response must satisfy.
    pub response_constraint: Option<Value>,
    /// Suppress the constraint's instructional input while keeping constrained
    /// decoding.
    pub omit_response_constraint_input: bool,
}

/// The only content type this backend supports.
pub(crate) const TEXT_KIND: &str = "text";

/// Languages the caller asked for, across inputs and outputs.
pub(crate) fn requested_languages(options: &CreateOptions) -> impl Iterator<Item = &str> {
    options
        .expected_inputs
        .iter()
        .chain(options.expected_outputs.iter())
        .flat_map(|expected| expected.languages.iter().map(String::as_str))
}

/// Whether every declared expectation names text content.
pub(crate) fn expects_text_only(options: &CreateOptions) -> bool {
    options
        .expected_inputs
        .iter()
        .chain(options.expected_outputs.iter())
        .all(|expected| expected.kind == TEXT_KIND)
}

/// Reject language tags that cannot be matched against model locales.
///
/// This is structural RFC 5646 validation only: whether a well-formed tag is
/// supported is the model's answer, and canonicalization belongs to the
/// JavaScript surface.
pub(crate) fn validate_languages(options: &CreateOptions) -> Result<(), Error> {
    for language in requested_languages(options) {
        if LanguageTag::parse(language).is_err() {
            return Err(Error::new(
                ErrorKind::InvalidInput,
                format!("`{language}` is not a well-formed language tag"),
            ));
        }
    }
    Ok(())
}

/// Reject message sequences the model cannot represent: a system message is
/// only valid as the first message of a conversation that is still empty.
pub(crate) fn validate_additions(history: &[Message], additions: &[Message]) -> Result<(), Error> {
    for (index, message) in additions.iter().enumerate() {
        if message.role != Role::System {
            continue;
        }
        if !history.is_empty() || index != 0 {
            return Err(Error::new(
                ErrorKind::InvalidInput,
                "a system message is only allowed as the first message of an empty conversation",
            ));
        }
    }
    Ok(())
}
